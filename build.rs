//! Splits `i18n/vocadada.ftl` (one message per text, one attribute per language) into one Fluent file
//! per language under `i18n/generated/`, which the app embeds and `tr!` checks against.
//! A missing translation is a warning and shows the English text as "[[...]]"; a missing English text,
//! an unknown language or other `$variables` than English fail the build.

use fluent_syntax::ast::{Entry, Identifier, Message, Pattern, PatternElement, Resource};
use fluent_syntax::{parser, serializer};
use std::collections::BTreeSet;
use std::fs;
use std::path::Path;

const SOURCE: &str = "i18n/vocadada.ftl";
const GENERATED: &str = "i18n/generated";
const REFERENCE: &str = "en";

fn main() {
    println!("cargo:rerun-if-changed={SOURCE}");
    // Also regenerate if the output was deleted (e.g. a fresh checkout or a manual clean-up).
    println!("cargo:rerun-if-changed={GENERATED}/{REFERENCE}/vocadada.ftl");
    let text = fs::read_to_string(SOURCE).unwrap_or_else(|e| panic!("{SOURCE}: {e}"));
    let resource = parser::parse(text.as_str()).unwrap_or_else(|(_, errors)| panic!("{SOURCE}: {errors:#?}"));
    let messages: Vec<&Message<&str>> = resource
        .body
        .iter()
        .filter_map(|entry| match entry {
            Entry::Message(m) => Some(m),
            _ => None,
        })
        .collect();
    // The languages, in the order of the first message (which therefore needs all of them).
    let languages: Vec<&str> = messages.first().expect("at least one message").attributes.iter().map(|a| a.id.name).collect();

    let errors: Vec<String> = messages.iter().flat_map(|m| check(m, &languages)).collect();
    if !errors.is_empty() {
        panic!("{SOURCE} has {} problem(s):\n{}", errors.len(), errors.join("\n"));
    }
    for message in &messages {
        let missing: Vec<_> = languages.iter().filter(|l| translation(message, l).is_none()).collect();
        if !missing.is_empty() {
            println!("cargo:warning={SOURCE}: {} not translated to {missing:?}, using \"[[English]]\"", message.id.name);
        }
    }

    for language in &languages {
        let body = resource
            .body
            .iter()
            .filter_map(|entry| match entry {
                Entry::Message(m) => {
                    let value = translation(m, language).cloned().unwrap_or_else(|| untranslated(m));
                    Some(Entry::Message(single(m.id.name, value)))
                }
                Entry::GroupComment(c) => Some(Entry::GroupComment(c.clone())),
                _ => None,
            })
            .collect();
        let content = format!(
            "# Generated by build.rs from {SOURCE}. Do not edit.\n\n{}",
            serializer::serialize(&Resource { body })
        );
        let path = Path::new(GENERATED).join(language).join("vocadada.ftl");
        // Only write on changes, so file timestamps don't trigger needless rebuilds.
        if fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(&path, content).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        }
    }
}

fn translation<'a, 's>(message: &'a Message<&'s str>, language: &str) -> Option<&'a Pattern<&'s str>> {
    message.attributes.iter().find(|a| a.id.name == language).map(|a| &a.value)
}

/// The English text marked as "[[...]]", so missing translations stand out in the app.
fn untranslated<'s>(message: &Message<&'s str>) -> Pattern<&'s str> {
    let english = translation(message, REFERENCE).expect("checked: English is required");
    let mut elements = vec![PatternElement::TextElement { value: "[[" }];
    elements.extend(english.elements.iter().cloned());
    elements.push(PatternElement::TextElement { value: "]]" });
    Pattern { elements }
}

fn single<'s>(id: &'s str, value: Pattern<&'s str>) -> Message<&'s str> {
    Message { id: Identifier { name: id }, value: Some(value), attributes: Vec::new(), comment: None }
}

/// Problems with one message: no English text, unknown languages, or `$variables` that differ from English.
fn check(message: &Message<&str>, languages: &[&str]) -> Vec<String> {
    let id = message.id.name;
    let mut errors = Vec::new();
    if message.value.is_some() {
        errors.push(format!("{id}: put the text into language attributes (`.en = ...`), not directly after `=`"));
    }
    let present: Vec<&str> = message.attributes.iter().map(|a| a.id.name).collect();
    let unknown: Vec<_> = present.iter().filter(|l| !languages.contains(l)).collect();
    if !unknown.is_empty() {
        errors.push(format!("{id}: unknown language(s) {unknown:?} (add them to the first message to use them)"));
    }
    let Some(reference) = translation(message, REFERENCE) else {
        errors.push(format!("{id}: the English text (`.{REFERENCE}`) is required"));
        return errors;
    };
    let expected = variables(id, reference);
    for attribute in &message.attributes {
        let found = variables(id, &attribute.value);
        if found != expected {
            errors.push(format!("{id}.{}: uses {found:?}, but {REFERENCE} uses {expected:?}", attribute.id.name));
        }
    }
    errors
}

fn variables(id: &str, pattern: &Pattern<&str>) -> BTreeSet<String> {
    let text = serializer::serialize(&Resource { body: vec![Entry::Message(single(id, pattern.clone()))] });
    text.split('$')
        .skip(1)
        .map(|rest| rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_' || *c == '-').collect())
        .collect()
}
